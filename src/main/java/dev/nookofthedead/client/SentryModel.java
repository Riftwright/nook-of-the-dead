    @Override
    public void setupAnim(SentryRenderer.State state) {
        super.setupAnim(state);
        float age = state.ageInTicks;
        float speed = Math.min(1.0F, state.walkAnimationSpeed);
        float wave = Mth.triangleWave(state.walkAnimationPos, 13.0F);
        this.head.yRot = Mth.clamp(state.yRot, -60.0F, 60.0F) * Mth.DEG_TO_RAD;
        this.head.xRot = Mth.clamp(state.xRot, -30.0F, 35.0F) * Mth.DEG_TO_RAD;
        // the legs: the knee bends as the leg swings back, the foot kept flat
        for (int s = 0; s < 2; s++) {
            float swing = (s == 0 ? -1.0F : 1.0F) * 0.9F * wave * speed;
            this.leg[s].xRot = swing;
            this.shin[s].xRot = Math.max(0.0F, swing) * 0.9F;
            this.foot[s].xRot = -(this.leg[s].xRot + this.shin[s].xRot);
        }
        // the trunk: a little forward as it goes, a heave as each foot comes down
        this.chest.xRot = 0.06F + 0.05F * speed;
        this.chest.y += Math.abs(wave) * 0.8F * speed;
        // the arms: swinging as a golem's, the forearms a little bent; both brought down to strike; the launcher held up
        float strike = state.attackTicksRemaining;
        for (int s = 0; s < 2; s++) {
            float side = s == 0 ? 1.0F : -1.0F;
            this.arm[s].zRot = side * 0.06F;
            this.arm[s].yRot = 0.0F;
            if (strike > 0.0F) {
                this.arm[s].xRot = -2.0F + 1.5F * Mth.triangleWave(strike, 10.0F);
                this.forearm[s].xRot = -0.1F;
            } else {
                this.arm[s].xRot = (-0.1F + side * 1.1F * wave) * speed;
                this.forearm[s].xRot = -0.25F - 0.1F * speed;
            }
            this.fist[s].xRot = 0.0F;
        }
        if (state.aiming && strike <= 0.0F) {              // the arm levelled at them, the launcher's barrel past the fist
            this.arm[0].xRot = -1.45F + this.head.xRot;
            this.arm[0].yRot = this.head.yRot * 0.7F;
            this.forearm[0].xRot = 0.0F;
            this.fist[0].xRot = 0.0F;
            this.arm[0].zRot = 0.0F;
        }
        this.antenna.zRot = Mth.sin(age * 0.11F) * 0.05F + wave * 0.12F * speed;
        this.antenna.xRot = -0.04F * speed;
    }
