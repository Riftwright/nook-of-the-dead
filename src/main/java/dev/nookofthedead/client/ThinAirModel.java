    @Override
    public void setupAnim(ZombieRenderState state) {
        super.setupAnim(state);
        if (this.tailBack == null) {
            return;                                          // an armour layer: the humanoid's parts only
        }
        float age = state.ageInTicks;
        // the head hung to one side, a little forward
        this.head.zRot += 0.3F;
        this.head.xRot += 0.12F;
        // the wind up there, in two gusts that never quite agree
        float wind = Mth.sin(age * 0.13F) * 0.06F + Mth.sin(age * 0.31F + 1.3F) * 0.03F;
        // the front tails pushed forward by the leg under them, the back one trailing
        this.tailFrontRight.xRot = Math.min(0.0F, this.rightLeg.xRot) * 0.9F + wind;
        this.tailFrontLeft.xRot = Math.min(0.0F, this.leftLeg.xRot) * 0.9F + wind * 0.8F;
        this.tailBack.xRot = Math.max(0.0F, Math.max(this.rightLeg.xRot, this.leftLeg.xRot)) * 0.7F + 0.08F + wind * 1.5F;
        this.tailSideRight.zRot = 0.06F + Math.abs(wind);
        this.tailSideLeft.zRot = -0.06F - Math.abs(wind);
        this.hairRight.zRot = 0.05F + wind * 0.5F;
        this.hairLeft.zRot = -0.05F + wind * 0.5F;
        this.hairBack.xRot = 0.08F + wind;
        this.ragsRight.zRot = wind;
        this.ragsLeft.zRot = -wind;
    }
