package dev.nookofthedead.world;

import java.util.HashMap;
import java.util.Map;

import org.jspecify.annotations.Nullable;

import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.util.RandomSource;
import net.minecraft.world.level.WorldGenLevel;
import net.minecraft.world.level.block.BarrelBlock;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.CampfireBlock;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.properties.BlockStateProperties;
import net.minecraft.world.level.levelgen.structure.BoundingBox;
import net.minecraft.world.level.levelgen.structure.templatesystem.StructurePlaceSettings;
import net.minecraft.world.level.levelgen.structure.templatesystem.StructureTemplate;

/**
 * The last holdouts on the roofs (the user, 2026-10-23, of office roofs with a shack on top: "全部やっていいと思う"):
 * the dead do not climb to a roof ({@code Mind#notices}), and some of the living knew it. On a flat stretch of a building's
 * roof, now and then, what one of them left: a bedroll, a cold fire, rainwater kept in a cauldron, a barrel of what they
 * had, a pole with a white rag for anyone who might see it, the diary - and sometimes the one who kept it, who never came
 * down. Where on each building is worked out from its template by {@code tools/roof_camps.py} ({@link #CAMPS}).
 */
public final class Rooftops {
    /** Of the buildings with room on their roof, how many in a hundred have a camp on it. */
    public static final int SHARE = 35;
    /** Of the camps, how many in a hundred still have their keeper. */
    public static final int KEPT = 45;

    // BEGIN GENERATED by tools/roof_camps.py
    static final String CAMPS = ""
            + "m1:55,10,24,3,4 m12:56,12,45,3,4 m14:8,25,10,3,4 m15:25,17,6,3,4 m16:15,27,47,3,4 m17:45,9,20,3,4 "
            + "m3:13,8,52,3,4 s12:15,19,12,3,4 s19:7,13,4,3,4 s2:25,13,9,3,4 s24:10,8,4,3,4 s25:9,22,19,4,3 s26:22,8,18,3,4 "
            + "s27:13,9,24,3,4 s28:4,8,22,3,4 xs15:7,23,4,3,4 xs24:1,9,2,3,4 xs25:1,8,1,3,4 ";
    // END GENERATED

    /** Each building's camp: its north-west corner (the roof under it) in the template's blocks, and its run (x, z). */
    static final Map<String, int[]> BY_BUILDING = new HashMap<>();

    static {
        for (String camp : CAMPS.trim().split(" ")) {
            if (camp.isEmpty()) {
                continue;
            }
            String[] kv = camp.split(":");
            String[] n = kv[1].split(",");
            BY_BUILDING.put(kv[0], new int[] {Integer.parseInt(n[0]), Integer.parseInt(n[1]), Integer.parseInt(n[2]),
                    Integer.parseInt(n[3]), Integer.parseInt(n[4])});
        }
    }

    /** Whether {@code lot}'s building has a camp on its roof: one with room for it, standing whole, one in a few. */
    public static int @Nullable [] camp(Town.Lot lot) {
        int[] camp = lot.building().map(id -> id.getPath().startsWith("town/") ? BY_BUILDING.get(id.getPath().substring(5)) : null).orElse(null);
        return camp != null && Math.floorMod(Town.hash(lot.seed(), 0, 0, 172), 100) < SHARE ? camp : null;
    }

    /** For commands: where on {@code lot} its camp stands, in the world (its keeper's place), if it has one. */
    public static @Nullable BlockPos where(net.minecraft.server.level.ServerLevel level, Town.Lot lot) {
        int[] c = camp(lot);
        StructureTemplate template = lot.building().flatMap(id -> level.getServer().getStructureTemplateManager().get(id)).orElse(null);
        if (c == null || template == null) {
            return null;
        }
        StructurePlaceSettings settings = new StructurePlaceSettings().setRotation(lot.rotation()).setMirror(lot.mirror());
        return new Camp(null, Town.placedAt(lot, template), settings, BoundingBox.infinite(), c).at(1, 1);
    }

    /**
     * Where on {@code lot} its camp stands, as {@link #where}, if it is there in the world: its cold fire on the roof (not on
     * ground first made before the camps were, 0.3 and before, nor on a roof since fallen in). Loads its chunk.
     */
    public static @Nullable BlockPos standing(net.minecraft.server.level.ServerLevel level, Town.Lot lot) {
        int[] c = camp(lot);
        StructureTemplate template = lot.building().flatMap(id -> level.getServer().getStructureTemplateManager().get(id)).orElse(null);
        if (c == null || template == null) {
            return null;
        }
        StructurePlaceSettings settings = new StructurePlaceSettings().setRotation(lot.rotation()).setMirror(lot.mirror());
        Camp camp = new Camp(null, Town.placedAt(lot, template), settings, BoundingBox.infinite(), c);
        return level.getBlockState(camp.at(0, 0)).is(Blocks.CAMPFIRE) ? camp.at(1, 1) : null;
    }

    /** The camp on {@code lot}'s roof, inside {@code box}, the building placed at {@code origin}; none on one fallen in or worn by sand. */
    static void draw(WorldGenLevel level, Town.Lot lot, BlockPos origin, StructurePlaceSettings settings, BoundingBox box, boolean whole) {
        int[] c = camp(lot);
        if (c == null || !whole) {
            return;
        }
        long h = Town.hash(lot.seed(), 1, 1, 173);
        RandomSource random = RandomSource.create(h);
        Camp camp = new Camp(level, origin, settings, box, c);
        camp.put(0, 0, Blocks.CAMPFIRE.defaultBlockState().setValue(CampfireBlock.LIT, false));
        camp.put(1, 0, Blocks.WATER_CAULDRON.defaultBlockState().setValue(BlockStateProperties.LEVEL_CAULDRON, 1 + (int) Math.floorMod(h, 2L)));
        camp.container(2, 0, "food", h >> 3);
        camp.put(0, 1, Blocks.CARPET.white().defaultBlockState());
        camp.put(0, 2, Blocks.CARPET.lightGray().defaultBlockState());
        for (int k = 0; k < 2; k++) {                                       // the pole and its white rag
            camp.put(0, 3, k, Blocks.SPRUCE_FENCE.defaultBlockState());
        }
        camp.put(0, 3, 2, Blocks.BANNER.white().defaultBlockState().setValue(BlockStateProperties.ROTATION_16, (int) Math.floorMod(h >> 9, 16L)));
        BlockPos book = camp.at(2, 2);
        if (box.isInside(book) && level.getBlockState(book).isAir()) {
            Props.pile(level, box, book, 1, random.nextFloat() * 360, random, () -> Diaries.book(random));
        }
        if (Math.floorMod(h >> 13, 2L) == 0) {
            camp.container(2, 3, "supplies", h >> 15);
        }
        BlockPos keeper = camp.at(2, 1);
        if (Math.floorMod(h >> 17, 100L) < KEPT && box.isInside(keeper) && level.getBlockState(keeper).isAir()) {
            Markers.remains(level, keeper, settings.getRotation().rotate(Direction.NORTH), RandomSource.create(h ^ 0x700F));
        }
    }

    /** One camp's cells: ({@code i}, {@code j}) across and along its stretch of roof, in the world. */
    private record Camp(WorldGenLevel level, BlockPos origin, StructurePlaceSettings settings, BoundingBox box, int[] c) {
        BlockPos at(int i, int j) {
            return this.at(i, j, 0);
        }

        BlockPos at(int i, int j, int up) {
            boolean alongZ = this.c[3] == 3;
            BlockPos local = new BlockPos(this.c[0] + (alongZ ? i : j), this.c[1] + 1 + up, this.c[2] + (alongZ ? j : i));
            return StructureTemplate.calculateRelativePosition(this.settings, local).offset(this.origin);
        }

        void put(int i, int j, BlockState state) {
            this.put(i, j, 0, state);
        }

        void put(int i, int j, int up, BlockState state) {
            BlockPos at = this.at(i, j, up);
            if (this.box.isInside(at) && this.level.getBlockState(at).isAir()) {
                this.level.setBlock(at, state, 2);
            }
        }

        void container(int i, int j, String loot, long seed) {
            BlockPos at = this.at(i, j);
            if (this.box.isInside(at) && this.level.getBlockState(at).isAir()) {
                Tower.container(this.level, this.box, at.getX(), at.getY(), at.getZ(),
                        Blocks.BARREL.defaultBlockState().setValue(BarrelBlock.FACING, Direction.UP), loot, seed);
            }
        }
    }

    private Rooftops() {}
}
