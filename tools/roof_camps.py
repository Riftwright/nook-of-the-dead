"""Where on each town building's roof a last holdout's camp can stand (world/Rooftops), worked out from the templates.

Run: python tools/roof_camps.py
reads src/main/resources/data/nookofthedead/structure/town/*.nbt and rewrites the generated CAMPS in world/Rooftops.java:
for each building with a flat stretch of roof three by four (or four by three) of full blocks, nothing over it, at least six
above the ground (the templates are taken out with two layers of earth under them), the highest such stretch - its
north-west corner in the template's own blocks, and which way it runs.
"""
import glob
import os

import refuge_hull as R

HERE = os.path.dirname(os.path.abspath(__file__))
TOWN = os.path.join(HERE, '..', 'src', 'main', 'resources', 'data', 'nookofthedead', 'structure', 'town')
JAVA = os.path.join(HERE, '..', 'src', 'main', 'java', 'dev', 'nookofthedead', 'world', 'Rooftops.java')
LOWEST = 8          # template y: six above the ground
SKIP = ('institute', 'institute_deep')
SOFT = ('torch', 'lantern', 'candle', 'carpet', 'snow', 'vine', 'cobweb', 'grass', 'fern', 'flower', 'button', 'lever', 'rail',
        'pressure_plate', 'sign', 'banner', 'skull', 'head', 'pot', 'sapling', 'bush', 'ladder', 'pane', 'bars', 'chain', 'rod',
        'structure_void', 'jigsaw', 'slab', 'stairs', 'fence', 'wall', 'trapdoor', 'door', 'leaves', 'glass', 'daylight')
EMPTY = ('air', 'cave_air', 'structure_void')


def camps():
    found = {}
    for path in sorted(glob.glob(os.path.join(TOWN, '*.nbt'))):
        name = os.path.basename(path)[:-4]
        if name in SKIP:
            continue
        root = R.read(path)
        names = [p.get('Name', p.get('id')) or '?' for p in root['palette']]
        top, full = {}, {}
        for b in root['blocks']:
            x, y, z = b['pos']
            short = names[b['state']].split(':')[-1]
            if short in EMPTY:
                continue
            if y >= top.get((x, z), -1):
                top[(x, z)] = y
                full[(x, z)] = not any(k in short for k in SOFT)
        best = None
        for (x, z), y in sorted(top.items()):
            if y < LOWEST or not full[(x, z)]:
                continue
            for w, d in ((3, 4), (4, 3)):
                if all(top.get((x + i, z + j)) == y and full.get((x + i, z + j)) for i in range(w) for j in range(d)):
                    if best is None or y > best[1]:
                        best = (x, y, z, w, d)
        if best:
            found[name] = best
    return found


def main():
    found = camps()
    text = ' '.join('%s:%d,%d,%d,%d,%d' % ((n,) + v) for n, v in sorted(found.items()))
    lines = []
    while text:
        cut = text.rfind(' ', 0, 110) if len(text) > 110 else len(text)
        lines.append(text[:cut].strip())
        text = text[cut:].strip()
    body = '    static final String CAMPS = ""\n' + '\n'.join('            + "%s "' % l for l in lines) + ';\n'
    src = open(JAVA, encoding='utf-8').read()
    a, b = '    // BEGIN GENERATED by tools/roof_camps.py\n', '    // END GENERATED\n'
    i, j = src.index(a) + len(a), src.index(b)
    open(JAVA, 'w', encoding='utf-8', newline='\n').write(src[:i] + body + src[j:])
    print('ok: %d buildings with a camp' % len(found))


if __name__ == '__main__':
    main()
